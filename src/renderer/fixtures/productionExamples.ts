import type {
  OutputEntry,
  OutputFile,
  ArtifactDescription,
} from '@/features/project/model/workspace.types';
import { scenes, character, locations } from './studio';
function document(id: string, name: string, artifact: ArtifactDescription): OutputFile {
  return {
    kind: 'file',
    id,
    name,
    format: 'json',
    content: JSON.stringify(artifact, null, 2),
    artifact,
  };
}
